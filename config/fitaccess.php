<?php

/*
|--------------------------------------------------------------------------
| FitAccess API — public address and accepted hosts (INSA CWE-20)
|--------------------------------------------------------------------------
| Absolute links generated by the API (reset links, file and photo URLs)
| always use `api_url`, never the request's Host header, and requests for any
| host not listed in `trusted_hosts` are rejected with 400.
|
| Note: APP_URL on the server is the web frontend (fitaccess.kalkidan.net),
| not this API, so it must not be used for API links.
*/

return [

    'api_url' => rtrim(env('API_PUBLIC_URL', 'https://fitaccess-api.kalkidan.net'), '/'),

    'trusted_hosts' => array_values(array_filter(array_map(
        'trim',
        explode(',', env('TRUSTED_HOSTS', 'fitaccess-api.kalkidan.net,www.fitaccess-api.kalkidan.net'))
    ))),

    // On in production by default; off for local development and tests.
    'enforce_trusted_hosts' => filter_var(
        env('ENFORCE_TRUSTED_HOSTS', env('APP_ENV') === 'production'),
        FILTER_VALIDATE_BOOL
    ),

];
